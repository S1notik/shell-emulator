package commands;

import java.util.List;

/**
 * Команда эмулятора.
 * <p>
 * Реализация не знает, куда попадёт её вывод: она возвращает текст,
 * а способ его отображения выбирает вызывающий код.
 */
public interface Command {
    /**
     * Выполняет команду.
     * @param args аргументы команды, без её имени
     * @return текст для вывода в терминал; пустая строка — ничего не выводить
     */
    String execute(List<String> args);
}
